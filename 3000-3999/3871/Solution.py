class Solution:
    def countCommas(self, n: int) -> int:
        if n < 1000:
            return 0
        if n < 1000000:
            return n - 999
        if n < 1000000000:
            return 2 * (n - 999999) + 999000
        if n < 1_000_000_000_000:
            return 3 * (n - 999_999_999) + 2 * (999_999_999 - 999_999) + 999_000
        if n < 1_000_000_000_000_000:
            return 4 * (n - 999_999_999_999) + 3 * (999_999_999_999 - 999_999_999) + 2 * (
                        999_999_999 - 999_999) + 999_000
        return 5 * (n - 999_999_999_999_999) + 4 * (999_999_999_999_999 - 999_999_999_999) + 3 * (
                    999_999_999_999 - 999_999_999) + 2 * (999_999_999 - 999_999) + 999_000
